declare(strict_types=1);

namespace ILIAS\ApiGateway\Application\Bootstrap;

use ILIAS\ApiGateway\Application\Factories\MiddlewareFactory;
use ILIAS\ApiGateway\Application\Middlewares;
use ILIAS\ApiGateway\Webservice\Domain\Webservice;
use Slim\App as SlimApp;

/**
 * Orchestrates the global middleware stack.
 *
 * SLIM 4 MIDDLEWARE EXECUTION ORDER (LIFO):
 * Middlewares are processed like an onion. The LAST middleware added here is the
 * FIRST to execute on the incoming Request. On the outgoing Response,
 * they execute in reverse order (First-In, Last-Out).
 *
 * @see https://www.slimframework.com/docs/v4/concepts/middleware.html#middleware-execution-order
 */
readonly class MiddlewarePipeline
{
    public function __construct(
        private Webservice $webservice,
        private MiddlewareFactory $middlewareFactory,
    ) {
    }

    /**
     * @param SlimApp<\Psr\Container\ContainerInterface> $application
     */
    public function apply(
        SlimApp $application,
        ErrorHandlerSetup $errorHandlerSetup,
    ): void {
        $webserviceMiddlewares = $this->webservice->getMiddlewares();

        foreach ($webserviceMiddlewares as $className) {
            $application->add($this->middlewareFactory->create($className));
        }

        $application->add(
            $this->middlewareFactory->create(Middlewares\RequestLoggingMiddleware::class)
        );

        $application->add(
            $this->middlewareFactory->create(Middlewares\RequestRateLimitingMiddleware::class)
        );

        /**
         * The routing middleware should be added earlier than the error middleware.
         * Otherwise exceptions thrown from it will not be handled by the middleware.
         */
        $application->addRoutingMiddleware();

        $application->add(
            $this->middlewareFactory->create(Middlewares\ApiServiceStatusMiddleware::class)
        );

        /**
         * The error middleware should be added last.
         * It will not handle any exceptions/errors for middleware added after it.
         */
        $errorHandlerSetup->register($application);

        /**
         * OUTER SHELL: Added last (LIFO) so security headers are applied
         * to all responses, including those generated by the ErrorHandler.
         */
        $application->add(
            $this->middlewareFactory->create(Middlewares\CorsMiddleware::class)
        );

        $application->add(
            $this->middlewareFactory->create(Middlewares\BrowserSecurityMiddleware::class)
        );

        $application->add(
            $this->middlewareFactory->create(Middlewares\TransportSecurityMiddleware::class)
        );
    }
}
